export function resolveCityId(value) {
  const key = String(value || "").trim().toLowerCase().replace(/[^a-z0-9-]/g, "");
  if (!key) return null;
  if (CITY_IDS.has(key)) return key;
  return CITY_ALIASES[key] || null;
}

export function getCity(id) {
  return CITY_PRESETS[resolveCityId(id) || "mumbai"];
}
